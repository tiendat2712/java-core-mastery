-- Trả lời phỏng vấn:
--   Ba lớp này đều cài đặt `Map<K, V>` nhưng khác nhau ở cấu trúc lưu trữ nội bộ,
--   thứ tự duyệt khóa và hiệu năng:
--   1. `HashMap<K, V>`: Dựa trên bảng băm (mảng `Node<K,V>[]` kết hợp danh sách liên
