-- Lưu ý / Bẫy phỏng vấn:
--   - Phân biệt `stream.toList()` (mới từ Java 16+) và `stream.collect(Collectors.toList())`:
--     * `stream.toList()` trả về một **Unmodifiable List** (gọi `add`/`remove`/`sort`
