--     bất biến thực sự phải dùng kiểu dữ liệu bất biến (`String`, `record`,
--     `List.of(...)`, hoặc tự thiết kế immutable class).
--   - Phân biệt `final` và "effectively final" (Java 8+): Một biến cục bộ dù không
