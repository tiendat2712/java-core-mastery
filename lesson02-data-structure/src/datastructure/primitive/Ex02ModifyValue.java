package datastructure.primitive;

public class Ex02ModifyValue {

    public static void main(String[] args) {
        // = --> Toan tu gan
        // VT = VP --> Lay gia tri cua VP gan cho VT

        int a = 5;
        int b = 7;
        System.out.println(a);
        System.out.println(b);

        b = 10;
        a = b;
        System.out.println(a);
    }

}
