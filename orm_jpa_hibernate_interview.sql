-- ORM-04 | Những API chính của JPA/Hibernate và cách dùng
-- =============================================================================
-- Trả lời phỏng vấn:
--   Ở phía JPA, các API trung tâm gồm `EntityManagerFactory` (thread-safe, tạo một
--   lần cho persistence unit), `EntityManager` (không thread-safe, đại diện cho
--   một persistence context để quản lý entity), `EntityTransaction` (quản lý giao
--   dịch `RESOURCE_LOCAL`) và bộ Query API (`TypedQuery`, `CriteriaBuilder`).
--   Tương ứng ở phía native Hibernate là `SessionFactory`, `Session`, `Transaction`
--   cùng `SelectionQuery` / `MutationQuery` (Hibernate 6). [O3,O4,O6,O7,O8]
--
-- Giải thích chi tiết các thao tác cốt lõi trên EntityManager / Session:
--   - `persist(entity)`: Đưa một entity mới (transient) vào trạng thái managed để
--     INSERT; đây không phải hàm upsert tổng quát cho mọi trạng thái.
--   - `find(Type.class, id)`: Tìm entity theo khóa chính, nếu không tồn tại sẽ trả
--     về `null`.
--   - `getReference(Type.class, id)`: Lấy một tham chiếu (thường là proxy) có thể
--     trì hoãn truy vấn DB tới khi truy cập thuộc tính; không dùng hàm này như
--     phép kiểm tra chắc chắn bản ghi tồn tại ngay lúc gọi.
--   - `merge(detached)`: Sao chép trạng thái của một object detached vào một
--     instance managed rồi trả về instance managed đó (chú ý: biến object truyền
--     vào hàm `merge` KHÔNG tự biến thành managed).
--   - `remove(managed)`: Đánh dấu xóa một entity đang managed.
--   - `flush()` / `clear()` / `detach()`: `flush()` đẩy các thay đổi đang chờ
--     xuống DB (nhưng chưa đồng nghĩa với `commit`); `clear()` và `detach()` tách
--     entity ra khỏi persistence context.
--   - Nhóm Query API: `TypedQuery`/`Query` (chạy JPQL), `CriteriaBuilder`/
--     `CriteriaQuery` (tạo truy vấn động an toàn kiểu), `createNativeQuery` (chạy
--     SQL gốc), `StoredProcedureQuery`.
--   - Phía Hibernate 6: Dùng `SessionFactory`/`Session`/`Transaction`,
--     `createSelectionQuery` (cho HQL đọc) và `createMutationQuery` (cho update/
--     delete). Có thể lấy `Session` từ JPA qua `em.unwrap(Session.class)`. [O7,O8]
--
-- Ví dụ truy vấn JPQL (dùng tên Entity và thuộc tính Java, không dùng tên bảng/cột):
--   var products = em.createQuery(
--       "select p from Product p where p.price >= :min order by p.price, p.id",
--       Product.class)
--       .setParameter("min", new BigDecimal("500000"))
--       .setMaxResults(10)
--       .getResultList();
--
-- Lưu ý / Bẫy phỏng vấn:
--   - Trong Hibernate 6 hiện đại, nên ưu tiên các phương thức chuẩn JPA như
--     `persist`, `merge`, `remove`; các hàm `save`, `update`, `saveOrUpdate` trong
--     tài liệu cũ đã bị deprecated, không nên coi là API mặc định hiện nay.
--   - Cơ chế Dirty Checking: Entity đang ở trạng thái managed khi bị sửa giá trị
--     field sẽ được tự động phát hiện và phát lệnh `UPDATE` lúc `flush`, không nhất
--     thiết phát `UPDATE` ngay tại dòng code gọi setter.
--   - Bẫy Bulk Update/Delete: Câu lệnh JPQL `UPDATE` hoặc `DELETE` hàng loạt chạy
--     thẳng xuống DB và bỏ qua việc cập nhật từng entity đang nằm trong persistence
--     context hiện tại, nên cần `flush`/`clear` hoặc đồng bộ lại context phù hợp
--     để tránh đọc phải dữ liệu cũ (stale state).
--
