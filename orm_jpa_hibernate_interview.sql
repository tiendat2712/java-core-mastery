-- ORM-05 | Phân biệt Lazy/Eager trong mapping và fetch
-- =============================================================================
-- Trả lời phỏng vấn:
--   `FetchType.EAGER` và `FetchType.LAZY` quy định thời điểm nạp dữ liệu của thuộc
--   tính hoặc quan hệ liên kết: `EAGER` yêu cầu provider nạp ngay dữ liệu liên kết
--   cùng lúc với entity cha, còn `LAZY` là chỉ dẫn (hint) để provider trì hoãn
--   việc nạp dữ liệu đó cho tới khi code thực sự truy cập vào. Theo chuẩn JPA 3.1,
--   mặc định `@ManyToOne` và `@OneToOne` là `EAGER`, còn `@OneToMany`,
--   `@ManyToMany` và `@ElementCollection` là `LAZY`. [O6,O9]
--
-- Giải thích chi tiết:
--   - Mapping trên entity đóng vai trò khai báo kế hoạch nạp (fetch plan) mặc định
--     tĩnh; trong thực tế thường chuyển `@ManyToOne` / `@OneToOne` sang `LAZY` rồi
--     chủ động nạp dữ liệu cần thiết theo từng câu query cụ thể (bằng `JOIN FETCH`,
--     `EntityGraph`, DTO projection hoặc batch fetching). [O9,O10]
--   - Cần phân biệt trong JPQL: `JOIN` thông thường chỉ phục vụ kết nối/lọc điều
--     kiện trong SQL mà không tự động khởi tạo (initialize) association trên
--     object kết quả; muốn nạp luôn association cùng entity gốc trong 1 câu query
--     thì phải dùng `JOIN FETCH`. [O10]
--
-- Ví dụ khai báo LAZY trên entity và chủ động JOIN FETCH theo ngữ cảnh:
--   // 1) Khai báo trong entity Order để tránh luôn tải Customer không cần thiết:
--   @ManyToOne(fetch = FetchType.LAZY)
--   @JoinColumn(name = "customer_id")
--   private Customer customer;
--
--   // 2) Khi màn hình chi tiết đơn hàng cần thông tin Customer, dùng JOIN FETCH:
--   // select o from Order o join fetch o.customer where o.id = :id
--
-- Lưu ý / Bẫy phỏng vấn:
--   - Theo đặc tả JPA, `LAZY` là một hint cho provider chứ không phải cam kết
--     tuyệt đối không bao giờ phát sinh SQL sớm trong mọi tình huống; ngược lại,
--     `EAGER` cũng không đồng nghĩa lúc nào provider cũng gộp thành 1 câu SQL
--     `JOIN` (provider hoàn toàn có thể phát các câu `SELECT` phụ).
--   - Bẫy N+1 Query: Để `LAZY` nhưng lại duyệt vòng lặp qua N đơn hàng rồi gọi
--     `order.getCustomer().getName()` sẽ phát sinh 1 câu query lấy danh sách đơn +
--     N câu query lẻ lấy từng khách hàng (tùy trạng thái cache và batch size).
--   - Bẫy `LazyInitializationException`: Truy cập vào một proxy hoặc collection
--     `LAZY` chưa được nạp sau khi `Session`/`EntityManager` đã đóng sẽ ném ngoại
--     lệ này. Cách xử lý đúng là nạp đủ dữ liệu cần dùng (qua `JOIN FETCH`,
--     `EntityGraph` hoặc DTO projection) khi persistence context còn mở, TUYỆT ĐỐI
--     không đổi bừa mọi mapping sang `EAGER` để né lỗi.
--   - Cẩn trọng khi `JOIN FETCH` các collection (`@OneToMany`) kết hợp phân trang
--     (`setFirstResult`/`setMaxResults`) hoặc fetch nhiều collection kiểu bag cùng
--     lúc vì sẽ làm nhân bản số dòng kết quả (Cartesian product) hoặc buộc
--     Hibernate phải phân trang trong bộ nhớ (in-memory pagination).
--   - Không nhầm lẫn giữa `fetch` và `cascade`: `fetch` quyết định việc đọc/nạp dữ
--     liệu từ DB, còn `cascade` (`CascadeType`) quyết định việc lan truyền các thao
--     tác ghi/xóa (`persist`, `merge`, `remove`) sang entity liên kết.
--
