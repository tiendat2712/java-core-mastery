-- ORM-03 | Phân biệt JDBC, JPA và Hibernate
-- =============================================================================
-- Trả lời phỏng vấn:
--   Ba khái niệm này nằm ở các tầng khác nhau khi làm việc với cơ sở dữ liệu trong
--   Java: JDBC là API mức thấp chuẩn của Java để gửi câu lệnh SQL và nhận
--   `ResultSet` qua driver; JPA (Jakarta Persistence) là bản đặc tả (specification)
--   và bộ interface chuẩn cho ORM trong Java; còn Hibernate ORM là một thư viện
--   triển khai cụ thể (provider) của đặc tả JPA, đồng thời cung cấp thêm các API
--   và tính năng riêng của Hibernate. [O1,O5,O6]
--
-- Giải thích chi tiết từng thành phần:
--   - JDBC: Cung cấp `Connection`, `PreparedStatement`, `ResultSet`. Lập trình
--     viên chủ động viết SQL và tự ánh xạ các cột sang object. [O5]
--   - JPA / Jakarta Persistence: Định nghĩa quy chuẩn ORM (`@Entity`, mapping
--     annotations, `EntityManager`, persistence context, JPQL, Criteria API). Bản
--     thân JPA chỉ là đặc tả và interface, cần một provider để chạy. [O6]
--   - Hibernate ORM: Là một JPA provider phổ biến (bên dưới vẫn giao tiếp với DB
--     thông qua JDBC), đồng thời có bộ API native riêng như `SessionFactory`,
--     `Session`, HQL và các tính năng mở rộng ngoài phạm vi JPA. [O1]
--
-- Ví dụ chuỗi gọi thường gặp trong kiến trúc ứng dụng:
--   Application -> JPA API -> Hibernate ORM -> JDBC Driver -> Database Server
--   (Hoặc ứng dụng có thể gọi trực tiếp Hibernate Session API, hoặc gọi JDBC thuần).
--
-- Lưu ý / Bẫy phỏng vấn:
--   - JPA không phải là một hệ quản trị CSDL, và Hibernate cũng không thay thế
--     Database Server hay JDBC Driver (Hibernate sinh SQL rồi gọi xuống JDBC).
--   - Ưu tiên viết code theo chuẩn JPA API để giảm phụ thuộc chặt vào một provider;
--     chỉ xuống native Hibernate API, native SQL hoặc JDBC thuần khi bài toán thực
--     sự cần tính năng đặc thù hoặc tối ưu hóa chuyên biệt.
--   - Phân biệt thêm với Spring Data JPA: Spring Data JPA là tầng trừu tượng hóa
--     repository (như `JpaRepository`) nằm phía trên JPA để giảm code boilerplate,
--     chứ không phải là tên gọi khác của JPA hay Hibernate.
--
