-- ORM-06 | First Level Cache và Second Level Cache
-- =============================================================================
-- Trả lời phỏng vấn:
--   First Level Cache (L1 Cache) là bộ nhớ đệm gắn liền với từng persistence
--   context (`EntityManager` / `Session`), luôn được bật mặc định để lưu các
--   entity đang managed theo định danh (ID) trong phạm vi một phiên làm việc.
--   Second Level Cache (L2 Cache) là bộ nhớ đệm cấp độ `EntityManagerFactory` /
--   `SessionFactory`, dùng chung giữa nhiều session khác nhau, mặc định tắt và
--   phải chủ động cấu hình cache provider, region cũng như đánh dấu các entity/
--   collection phù hợp. [O8,O10,O11]
--
-- Giải thích chi tiết:
--   - First Level Cache (L1): Đảm bảo tính đồng nhất đối tượng (repeatable read ở
--     tầng object) trong cùng một persistence context: truy vấn theo ID lần thứ
--     hai cho một entity đã nằm trong L1 sẽ trả về đúng instance Java đó mà không
--     cần bắn lại câu lệnh `SELECT`. Khi gọi `clear()`, `detach()` hoặc `close()`,
--     phạm vi L1 đối với các entity đó kết thúc. [O8]
--   - Second Level Cache (L2): Chia sẻ dữ liệu giữa các session. Lưu ý quan trọng
--     là L2 thường lưu trữ dữ liệu ở dạng trạng thái tách rời (dehydrated state)
--     chứ KHÔNG chia sẻ chung một instance entity Java khả biến (mutable) cho
--     nhiều thread/session cùng sửa; mỗi session khi lấy từ L2 sẽ dựng lại
--     instance managed riêng của mình. [O10,O11]
--   - Query Cache: Là lớp cache riêng dành cho tập kết quả của câu truy vấn; chỉ
--     bật L2 Cache thôi thì các câu JPQL/HQL chưa tự động được cache mà phải bật
--     thêm cấu hình Query Cache và đánh dấu từng query là cacheable. [O10]
--
-- Ví dụ minh họa hành vi của L1 Cache và L2 Cache:
--   // 1) Trong cùng một EntityManager (L1 Cache):
--   Product a = em.find(Product.class, 1L); // Chạy SELECT (nếu chưa có trong cache)
--   Product b = em.find(Product.class, 1L); // Lấy từ L1, không SELECT lại; (a == b) là true
--
--   // 2) Giữa hai Session khác nhau khi đã cấu hình L2 Cache cho Product:
--   // Session A đọc Product(1L) rồi đóng -> trạng thái được lưu ở L2 Cache.
--   // Session B gọi find(Product.class, 1L) -> lấy trạng thái từ L2 (nếu còn hợp lệ)
--   // để tạo ra một instance Product managed riêng thuộc về Session B.
--
-- Lưu ý / Bẫy phỏng vấn:
--   - Không hiểu nhầm rằng chỉ cần gắn `@Cacheable` là có L2 Cache: phải cấu hình
--     cả thư viện/provider L2 (như JCache/Ehcache/Infinispan...) và bật trong cấu
--     hình Hibernate.
--   - Ngay cả khi một số entity đã nằm trong L1 Cache, việc chạy một câu truy vấn
--     JPQL thông thường vẫn sẽ thực thi câu lệnh SQL xuống DB vì L1 Cache tra cứu
--     theo khóa chính chứ không phải bộ máy thực thi câu query tổng quát.
--   - Cách lưu trữ bên trong của Query Cache phụ thuộc vào phiên bản và cấu hình
--     Hibernate (ví dụ cơ chế shallow/full), nên tránh phát biểu rập khuôn rằng
--     "mọi query cache trong mọi phiên bản luôn chỉ lưu danh sách ID".
--   - L2 Cache chỉ phù hợp với dữ liệu đọc nhiều, ít thay đổi; nếu DB bị cập nhật
--     trực tiếp bởi ứng dụng khác không đi qua Hibernate thì L2 sẽ giữ dữ liệu cũ
--     (stale data) trừ khi có cơ chế invalidation/eviction (`factory.getCache()`).
--
-- =============================================================================
-- ORM-07 | Phân biệt getCurrentSession và openSession
-- =============================================================================
-- Trả lời phỏng vấn:
--   `openSession()` và `getCurrentSession()` là hai phương thức của interface
--   `SessionFactory` trong native Hibernate (không phải phương thức của JPA):
--   `openSession()` luôn khởi tạo một `Session` hoàn toàn mới và người gọi phải tự
--   chịu trách nhiệm quản lý vòng đời cũng như gọi `close()`; trong khi đó,
--   `getCurrentSession()` trả về `Session` đang gắn với ngữ cảnh hiện tại (do cấu
--   hình `CurrentSessionContext` quyết định, chẳng hạn gắn với JTA transaction,
--   thread hoặc Spring transaction context). [O7,O10]
--
-- Giải thích chi tiết:
--   - `openSession()`: Mỗi lần gọi tạo ra một `Session` (persistence context) độc
--     lập mới. Việc mở session không tự động bắt đầu DB transaction; lập trình
--     viên phải chủ động mở/đóng transaction và đóng session (thường dùng
--     try-with-resources). [O7]
--   - `getCurrentSession()`: Tra cứu `Session` theo chiến lược ngữ cảnh đã cấu
--     hình (`jta`, `thread`, `managed` hoặc custom implementation). Nếu gọi nhiều
--     lần trong cùng một ngữ cảnh đang hoạt động, nó trả về cùng một `Session`.
--     Nếu gọi khi chưa có ngữ cảnh/transaction hợp lệ được thiết lập theo yêu cầu
--     của chiến lược đó, Hibernate có thể ném lỗi. [O7,O10]
--
-- Ví dụ chủ động quản lý vòng đời với openSession():
--   try (Session session = factory.openSession()) {
--       Transaction tx = session.beginTransaction();
--       try {
--           session.persist(new Product("Chuột", new BigDecimal("250000")));
--           tx.commit();
--       } catch (RuntimeException ex) {
--           if (tx.isActive()) tx.rollback();
--           throw ex;
--       }
--   }
--
-- Ví dụ ngữ cảnh của getCurrentSession():
--   - Khi dùng `hibernate.current_session_context_class=thread`:
--     `ThreadLocalSessionContext` gắn session với thread hiện hành và có cơ chế tự
--     đóng khi transaction hoàn tất (chi tiết hành vi phụ thuộc implementation). [O12]
--   - Khi dùng ngữ cảnh `managed` (`ManagedSessionContext`): Tầng bên ngoài phải
--     chủ động bind/unbind `Session` cũng như quản lý flush/close. [O13]
--   - Khi dùng chung với Spring (`@Transactional`) hoặc JTA: Transaction manager
--     của framework quản lý vòng đời session, ta không tự ý gọi `close()` lên
--     session lấy từ `getCurrentSession()`.
--
-- Lưu ý / Bẫy phỏng vấn:
--   - Tránh phát biểu tuyệt đối rằng "`getCurrentSession()` luôn gắn với mỗi
--     thread" hoặc "luôn tự tạo session mới mọi lúc", vì hành vi chính xác phụ
--     thuộc vào implementation của `CurrentSessionContext` đang được cấu hình.
--   - Dù lấy từ `openSession()` hay `getCurrentSession()`, đối tượng `Session`
--     ĐỀU KHÔNG thread-safe; tuyệt đối không chia sẻ một `Session` cho nhiều luồng
--     xử lý song song.
--   - Mở `Session` cũng không đồng nghĩa với việc luôn chiếm giữ cứng một JDBC
--     `Connection` suốt toàn bộ thời gian sống của session, vì thời điểm mượn/trả
--     connection còn phụ thuộc vào `PhysicalConnectionHandlingMode` của Hibernate.
--
