-- ORM-01 | ORM là gì?
-- =============================================================================
-- Trả lời phỏng vấn:
--   ORM (Object-Relational Mapping) là kỹ thuật ánh xạ giữa mô hình hướng đối
--   tượng trong ngôn ngữ lập trình (class/entity, thuộc tính, định danh, liên kết
--   object) và mô hình dữ liệu quan hệ trong cơ sở dữ liệu (bảng, cột, khóa chính,
--   khóa ngoại). ORM provider (như Hibernate) tự động chuyển các thao tác trên
--   entity thành câu lệnh SQL, đọc dữ liệu từ bảng thành object và theo dõi thay
--   đổi trạng thái của các entity đang được quản lý (managed). [O1]
--
-- Giải thích chi tiết:
--   - Giảm mã lặp lại khi phải đọc từng cột từ `ResultSet` sang object và ngược lại.
--   - Thống nhất các thao tác CRUD, quản lý vòng đời entity (transient/new,
--     managed/persistent, detached, removed) và hỗ trợ ánh xạ các mối quan hệ.
--
-- Ví dụ ánh xạ khái niệm:
--   Class `Product(id, name, price)` ánh xạ tới bảng `product(id, name, price)`;
--   thuộc tính quan hệ đối tượng `Order.customer` trên Java được lưu dưới dạng cột
--   khóa ngoại `customer_id` trong bảng `orders` dưới DB.
--
-- Lưu ý / Bẫy phỏng vấn:
--   - Dùng ORM KHÔNG loại bỏ nhu cầu hiểu sâu về SQL, transaction, index, JOIN hay
--     execution plan; cấu hình fetch plan không phù hợp vẫn dễ gây lỗi hiệu năng
--     như N+1 query hoặc tải dư thừa dữ liệu vào bộ nhớ.
--   - Không phát biểu cứng nhắc "1 entity luôn ánh xạ đúng 1 bảng": trong thực tế
--     một entity có thể trải trên nhiều bảng (`@SecondaryTable`, kế thừa `JOINED`/
--     `TABLE_PER_CLASS`), hoặc nhiều class cùng nằm trong một bảng (`SINGLE_TABLE`,
--     `@Embedded` / `@Embeddable`).
--
